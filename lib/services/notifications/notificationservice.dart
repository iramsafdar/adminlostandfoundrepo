  // init
  // This function is all about setting up local notifications on the device,
  // so the app can show a notification popup when a Firebase message arrives
  void initLocalNotification(
      BuildContext context, RemoteMessage message) async {
    // context → Flutter context, needed for navigation if user taps the notification.
    // message → the Firebase message object, containing title, body, and data.
    var androidInitSetting = const AndroidInitializationSettings(
      '@mipmap/ic_launcher',
    );
    //AndroidInitializationSettings tells Flutter which icon to use for notifications on Android.
    // @mipmap/ic_launcher → the default app icon
    // You can use your custom icon if you want.
    // ✅ Simple meaning:
    // “On Android, show this icon in the notification.”

    var iosInitSetting = const DarwinInitializationSettings();
    // It sets up iOS notifications defaults (sound, badge, alert).
    // ✅ Simple meaning:
    // “On iOS, use default notification behavior.”

    var initializationSetting = InitializationSettings(
      android: androidInitSetting,
      iOS: iosInitSetting,
    );
    // FlutterLocalNotificationsPlugin requires a single object containing both Android & iOS settings.
    //
    // This InitializationSettings object is what we pass to the plugin.
    // ✅ Simple meaning:
    // “Here’s how notifications should look on Android and iOS.”

    await _flutterLocalNotificationPlugin.initialize(
      initializationSetting,
      onDidReceiveNotificationResponse: (payload) {
        handleMessage(context, message);
      },
    );
    //   This line actually sets up local notifications on the device.
    // onDidReceiveNotificationResponse → what happens when user taps the notification:
    // Here, you call handleMessage(context, message)
    // This means: open the correct screen when the notification is tapped.
    // ✅ Simple meaning:
    // “Set up notifications and define what happens if user taps it.”
  }

  // firebase init
  void firebaseInit(BuildContext context) {
    // Takes context because we may need it to navigate to a screen when notification is tapped.

    //when app is runnign in foreground..
    FirebaseMessaging.onMessage.listen((message) {
      // FirebaseMessaging.onMessage → fires whenever a notification arrives while the app is in the foreground (open).
      // message contains:
      // title → notification title
      // body → notification body
      // data → extra info like chat ID
      // ✅ Simple meaning:
      // “Whenever a notification comes while app is open, run this code.”
      RemoteNotification? notification = message.notification;
      // notification → the main notification (title, body)
      AndroidNotification? android = message.notification?.android;
      // android → Android-specific info (like channel ID, importance)
      // Simple meaning:
      // “Get the info from the message so we can show it.”

      if (kDebugMode) {
        print("notification title: ${notification?.title}");
        print("notification body: ${notification?.body}");
      }
      //ios
      if (Platform.isIOS) {
        iosForegroundMessage();
      }
      // On iOS, notifications don’t automatically appear if the app is open.
      // iosForegroundMessage() tells iOS: “Show alert, badge, and play sound even if app is open.
      // ✅ Simple meaning:
      // “For iOS, make sure user sees the notification even if app is open.”


      //android
      if (Platform.isAndroid) {
        initLocalNotification(context, message);
        //handleMessage(context, message);
        showNotification(message);
        //   Android also doesn’t automatically display notifications exactly how you want.
        // initLocalNotification(context, message) → sets up notification appearance
        // showNotification(message) → actually shows the popup on screen
      }
    });
  }



  // This section is about how notifications are shown and handled in your app — both when the app is open, in background, or terminated.

  //function to show notifications
  Future<void> showNotification(RemoteMessage message) async {
    // This function actually displays a notification popup on the phone.

    AndroidNotificationChannel channel = AndroidNotificationChannel(
      message.notification!.android!.channelId.toString(),
      message.notification!.android!.channelId.toString(),
      importance: Importance.high,
      showBadge: true,
      playSound: true,

      //   Creates a notification channel for Android (required on Android 8+).
      // importance: high → makes sure the notification pops up visibly and makes sound.
      // showBadge: true → shows a number on app icon.
      // playSound: true → plays notification sound.

      // 🔔 Why do we need to create a Notification Channel
      // On Android 8.0 (API 26) and above, Android will NOT show any notification unless it belongs to a notification channel.
      //  👉 If you don’t create a channel → notification may not appear
      //   🧠 What is a Notification Channel?
      // Think of a channel as a category for notifications.
      // Example categories:
      // Chat messages
      // Order updates
      // Promotions
      // Alerts
      // Each channel has its own settings like:
      // Sound
      // Vibration
      // Importance (high / low)
      // Badge
      // Users can control these from phone settings.

      // ✔ Firebase message contains a channel ID
      // ✔ You create the same channel locally
      // ✔ Android matches them
      // ✔ Then Android shows notification correctly

    );
    //android setting
    AndroidNotificationDetails androidNotificationDetails =
    AndroidNotificationDetails(
      channel.id.toString(),
      channel.name.toString(),
      channelDescription: "Channel Description",
      importance: Importance.high,
      priority: Priority.high,
      playSound: true,
      sound: channel.sound,
      //   Detailed Android settings for the notification.
      // Controls: priority, sound, badge, channel, etc.
    );
    //ios setting
    DarwinNotificationDetails darwinNotificationDetails =
    const DarwinNotificationDetails(
      presentAlert: true,
      presentBadge: true,
      presentSound: true,
      //   iOS notification settings.
      // presentAlert: true → show popup
      // presentBadge: true → show number on app icon
      // presentSound: true → play sound
    );
    //merge setting
    NotificationDetails notificationDetails = NotificationDetails(
      android: androidNotificationDetails,
      iOS: darwinNotificationDetails,
      //   Combines Android + iOS settings into one object for Flutter to use.
    );
    //show notfication
    Future.delayed(Duration.zero, () { //"Run this right after Flutter finishes what it’s doing now."

      _flutterLocalNotificationPlugin.show(
        0,
        message.notification!.title.toString(),
        message.notification!.body.toString(),
        notificationDetails,
        payload: "my_data",
        //   this actually shows the notification popup on screen.
        // title → notification title
        // body → notification body
        // payload → extra data (can be used when user taps notification)
        // ✅ Simple summary:
        // This function shows the notification exactly how you want it on Android and iOS.



        //   payload is extra hidden data attached to the notification.
        // It is mainly used when:
        // 👉 User taps the notification
        // 👉 Your app opens
        // 👉 You can read this payload and decide what screen to open

        //   ✅ Example use
        // payload: "open_chat"
        // Later:
        // onDidReceiveNotificationResponse: (response) {
        //   print(response.payload);   // open_chat
        // }
        // So you can do:
        // if (response.payload == "open_chat") {
        //    // Navigate to Chat Screen
        // }


      );
    });
  }

  //background and terminated
  // This function handles when the user taps a notification while the app is backgrounded or terminated.
  Future<void> setupInteractMessage(BuildContext context) async {
    // background state
    FirebaseMessaging.onMessageOpenedApp.listen(
      // Background state: app is open but in background.
      // Triggered when user taps a notification.
      // Calls handleMessage() to navigate to the right screen.
          (message) {
        handleMessage(context, message);
      },
    );

    // terminated state
    FirebaseMessaging.instance.getInitialMessage().then(
      // Was the app opened by tapping a notification when the app was CLOSED?
      // If yes → it gets that notification → then runs your function.
          (RemoteMessage? message) {
        if (message != null && message.data.isNotEmpty) {
          handleMessage(context, message);
          //   This ensures tapping a notification opens the correct screen whether app is backgrounded or fully closed.

        }
      },
    );
  }

