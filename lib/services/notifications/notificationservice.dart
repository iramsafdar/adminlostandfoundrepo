  // Asking Notification Permission
  void requestNotificationPermission() async {
    NotificationSettings settings = await messaging.requestPermission(
      alert: true, //show popup notifications
      announcement: true, //Siri can read it (iOS)
      badge: true, //show number on app icon
      carPlay: true, //show in car screen (iOS)
      criticalAlert: true, //allow urgent alerts
      provisional: true, //allow silent notifications first (iOS)
      sound: true, //play sound
    );

    if (settings.authorizationStatus == AuthorizationStatus.authorized) {
      // User said YES
      // 👉 Notifications are fully allowed
      print('User granted permission');
    } else if (settings.authorizationStatus == AuthorizationStatus.provisional) {
      // User didn’t say a full yes, but allowed:
      // Notifications silently
      // No popup, no sound
      print('User provisional granted permission');
    } else {
      // User denied notification permission
      // So you do two things:
      Get.snackbar(
        "Notification permission denied",
        "Please allow Notification to recieve updates.",
        // Shows a small message to explain
        // “Notifications are off. Please enable them.”
        snackPosition: SnackPosition.BOTTOM,
      );
      // Open app notification settings
      // After 2 seconds, the app
      // Opens the phone’s notification settings
      // User can manually turn notifications ON
      Future.delayed(const Duration(seconds: 2), () {
        AppSettings.openAppSettings(type: AppSettingsType.notification);
      });
    }
  }

